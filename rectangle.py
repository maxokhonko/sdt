def area(a: float, b: float) -> float:
    """Calculates the area of a rectangle with sides a and b.

    Example:
        area(4, 5)  # 20.0
    """
    return a * b


def perimeter(a: float, b: float) -> float:
    """Calculates the perimeter of a rectangle with sides a and b.

    Example:
        perimeter(4, 5)  # 18.0
    """
    return 2 * (a + b)