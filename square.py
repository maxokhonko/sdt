def area(a: float) -> float:
    """Calculates the area of a square with side a.

    Example:
        area(6)  # 36.0
    """
    return a * a


def perimeter(a: float) -> float:
    """Calculates the perimeter of a square with side a.

    Example:
        perimeter(6)  # 24.0
    """
    return 4 * a
